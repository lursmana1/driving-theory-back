/**
 * Creates question_progress (mistake trainer / study plan state) and, with
 * --backfill, fills it from existing answer history. Safe to re-run.
 *
 *   npx ts-node -r tsconfig-paths/register scripts/ensure-question-progress.ts
 *   ... --backfill --dry-run   # counts only, writes nothing but the table
 *   ... --backfill             # replay history into question_progress
 *   ... --print-sql [--backfill] [--dry-run] > qp.sql
 *                              # no DB connection: print the same work as one
 *                              # psql script (for the Coolify psql terminal)
 *
 * Order for a deploy: create the table AND run the backfill while the old API
 * is still serving, then deploy. The new API reads question_progress in
 * GET /auth/me and writes it on every exam and practice answer, so those fail
 * while the table is missing; the old API never touches it, so the backfill
 * cannot race live writes.
 *
 * Backfill only touches (user, question) pairs that have no progress row
 * yet, so re-running it never double-counts. It replays exam answers and
 * graded practice answers (live questions only) in answer order, one round
 * per answer index, inside one transaction. A pair whose row already holds a
 * newer answer (written live after the history snapshot) is left alone
 * instead of having old history replayed over it. Practice keeps only the
 * last answer per question, so practice-heavy schedules are approximate; they
 * settle after the next review.
 */
import 'dotenv/config';
import { initPg } from './lib/pg-data-source';
import { upsertQuestionProgressSql } from '../src/question-progress/question-progress.sql';

const args = new Set(process.argv.slice(2));
const BACKFILL = args.has('--backfill');
const DRY_RUN = args.has('--dry-run');
const PRINT_SQL = args.has('--print-sql');

const SCHEMA_SQL: readonly string[] = [
  `CREATE TABLE IF NOT EXISTS question_progress (
    "userId" integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    "questionId" integer NOT NULL,
    "wrongCount" integer NOT NULL DEFAULT 0,
    "correctCount" integer NOT NULL DEFAULT 0,
    box smallint NOT NULL DEFAULT 0,
    "reviewsLeft" smallint NOT NULL DEFAULT 0,
    "lastResult" boolean NOT NULL,
    "firstAnsweredAt" timestamptz NOT NULL,
    "lastAnsweredAt" timestamptz NOT NULL,
    "lastReviewedAt" timestamptz NULL,
    "dueAt" timestamptz NULL,
    "clearedAt" timestamptz NULL,
    CONSTRAINT pk_question_progress PRIMARY KEY ("userId", "questionId")
  )`,
  `CREATE INDEX IF NOT EXISTS idx_question_progress_user_due
    ON question_progress ("userId", "dueAt")
    WHERE "dueAt" IS NOT NULL`,
];

const HISTORY_SQL = `
  CREATE TEMP TABLE qp_history ON COMMIT DROP AS
  SELECT
    h.user_id,
    h.question_id,
    h.correct,
    h.answered_at,
    ROW_NUMBER() OVER (
      PARTITION BY h.user_id, h.question_id
      ORDER BY h.answered_at, h.source, h.row_id
    )::int AS rn
  FROM (
    SELECT t."userId" AS user_id, a."questionId" AS question_id, a.correct,
           a."createdAt" AS answered_at, 0 AS source, a.id AS row_id
    FROM user_answers a
    INNER JOIN exam_attempts t ON t.id = a."attemptId"
    WHERE EXISTS (
      SELECT 1 FROM questions q WHERE q.id = a."questionId" AND q.lang = t.lang
    )
    UNION ALL
    SELECT p."userId", p."questionId", p.correct,
           p."updatedAt", 1, p.id
    FROM practice_answers p
    WHERE p.correct IS NOT NULL
      AND EXISTS (
        SELECT 1 FROM questions q WHERE q.id = p."questionId" AND q.lang = p.lang
      )
  ) h
  WHERE NOT EXISTS (
    SELECT 1 FROM question_progress qp
    WHERE qp."userId" = h.user_id AND qp."questionId" = h.question_id
  )
`;

const HISTORY_STATS_SQL = `
  SELECT COUNT(*)::int AS answers,
         COUNT(DISTINCT (user_id, question_id))::int AS pairs,
         COALESCE(MAX(rn), 0)::int AS rounds
  FROM qp_history
`;

/**
 * Replays history round `roundExpr` (a bind parameter or PL/pgSQL variable).
 * Rounds run in answer order, so a row this backfill wrote never holds a
 * newer answer; one that does was written live and is skipped.
 */
function roundSql(roundExpr: string): string {
  return `
  WITH up AS (${upsertQuestionProgressSql(`(
    SELECT h.user_id, h.question_id, h.correct, h.answered_at
    FROM qp_history h
    WHERE h.rn = ${roundExpr}
      AND NOT EXISTS (
        SELECT 1 FROM question_progress live
        WHERE live."userId" = h.user_id
          AND live."questionId" = h.question_id
          AND live."lastAnsweredAt" > h.answered_at
      )
  )`)}
  )
  SELECT COUNT(*)::int AS n FROM up`;
}

/** The same work as `main`, as one psql script that stops on any error. */
function buildPsqlScript(): string {
  const lines = [
    '-- Generated by scripts/ensure-question-progress.ts --print-sql',
    '\\set ON_ERROR_STOP on',
    'BEGIN;',
    ...SCHEMA_SQL.map((sql) => `${sql};`),
  ];
  if (BACKFILL) {
    lines.push(
      `${HISTORY_SQL.trim()};`,
      'CREATE INDEX ON qp_history (rn);',
      `${HISTORY_STATS_SQL.trim()};`,
    );
    if (!DRY_RUN) {
      lines.push(`DO $backfill$
DECLARE
  v_rounds int;
  v_n int;
BEGIN
  SELECT COALESCE(MAX(rn), 0) INTO v_rounds FROM qp_history;
  FOR v_round IN 1..v_rounds LOOP
    ${roundSql('v_round').trim()} INTO v_n;
    IF v_round = 1 OR v_round % 10 = 0 OR v_round = v_rounds THEN
      RAISE NOTICE 'round %/%: % answers', v_round, v_rounds, v_n;
    END IF;
  END LOOP;
END
$backfill$;`);
    }
  }
  lines.push(
    `SELECT COUNT(*)::int AS progress_rows,
       COUNT(*) FILTER (WHERE "dueAt" IS NOT NULL)::int AS active_mistakes
FROM question_progress;`,
    DRY_RUN ? 'ROLLBACK;' : 'COMMIT;',
  );
  return `${lines.join('\n\n')}\n`;
}

function describeTarget(): string {
  const url = process.env.DATABASE_URL;
  if (url) {
    const parsed = new URL(url);
    return `${parsed.hostname}:${parsed.port || '5432'}${parsed.pathname}`;
  }
  return `${process.env.PG_HOST || 'localhost'}:${process.env.PG_PORT || '5432'}/${process.env.PG_DATABASE || 'driving_theory_back'}`;
}

async function main() {
  if (PRINT_SQL) {
    process.stdout.write(buildPsqlScript());
    return;
  }

  console.log(`target: ${describeTarget()}`);
  const ds = await initPg();
  const qr = ds.createQueryRunner();
  try {
    await qr.connect();
    for (const sql of SCHEMA_SQL) await qr.query(sql);
    console.log('question_progress table + index ready');
    if (!BACKFILL) return;

    await qr.startTransaction();
    await qr.query(HISTORY_SQL);
    await qr.query(`CREATE INDEX ON qp_history (rn)`);
    const [stats] = (await qr.query(HISTORY_STATS_SQL)) as {
      answers: number;
      pairs: number;
      rounds: number;
    }[];
    console.log(
      `history to replay: ${stats.answers} answers, ${stats.pairs} new (user, question) pairs, ${stats.rounds} rounds`,
    );

    if (DRY_RUN) {
      await qr.rollbackTransaction();
      console.log('dry run: nothing written');
      return;
    }

    const started = Date.now();
    const round = roundSql('$1');
    for (let rn = 1; rn <= stats.rounds; rn++) {
      const [{ n }] = (await qr.query(round, [rn])) as { n: number }[];
      if (rn === 1 || rn % 10 === 0 || rn === stats.rounds) {
        console.log(`round ${rn}/${stats.rounds}: ${n} answers`);
      }
    }
    await qr.commitTransaction();
    console.log(`backfill committed in ${Date.now() - started} ms`);
  } catch (err) {
    if (qr.isTransactionActive) await qr.rollbackTransaction();
    throw err;
  } finally {
    await qr.release();
    await ds.destroy();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
